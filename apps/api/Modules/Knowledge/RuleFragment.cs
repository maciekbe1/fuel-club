using FuelClub.Api.Infrastructure;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using NpgsqlTypes;

namespace FuelClub.Api.Modules.Knowledge;

/// <summary>A searchable point of an approved program rules version. Written only by migrations.</summary>
public sealed class RuleFragment
{
    public Guid Id { get; set; }
    public required string DocumentVersion { get; set; }

    /// <summary>"3.2" for §3.2.</summary>
    public required string Section { get; set; }
    public required string Heading { get; set; }
    public required string Text { get; set; }

    /// <summary>Heading and text, lower case without diacritics (PolishText.Normalize).</summary>
    public required string SearchText { get; set; }

    /// <summary>Generated by the database from SearchText ('simple': no stemming, no stop words).</summary>
    public NpgsqlTsVector SearchVector { get; set; } = null!;
}

public sealed class RuleFragmentConfiguration : IEntityTypeConfiguration<RuleFragment>
{
    public void Configure(EntityTypeBuilder<RuleFragment> builder)
    {
        builder.ToTable(
            "RuleFragments",
            table =>
            {
                table.HasCheckConstraint(
                    "CK_RuleFragments_Section",
                    "\"Section\" ~ '^[1-9][0-9]?\\.[1-9][0-9]?$'"
                );
                // The index only works on normalized text: the query side normalizes the same way.
                table.HasCheckConstraint(
                    "CK_RuleFragments_SearchText",
                    "\"SearchText\" = lower(\"SearchText\")"
                );
            }
        );
        builder.Property(f => f.DocumentVersion).HasMaxLength(32);
        builder.Property(f => f.Section).HasMaxLength(8);
        builder.Property(f => f.Heading).HasMaxLength(100);
        builder.Property(f => f.Text).HasMaxLength(2000);
        builder.Property(f => f.SearchText).HasMaxLength(2200);
        builder.HasIndex(f => new { f.DocumentVersion, f.Section }).IsUnique();
        builder
            .HasGeneratedTsVectorColumn(f => f.SearchVector, "simple", f => new { f.SearchText })
            .HasIndex(f => f.SearchVector)
            .HasMethod("GIN");
    }
}
